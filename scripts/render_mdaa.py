"""
Render infra/mdaa.template.yaml + config/environments/<env>.yaml into ./mdaa.yaml (git-ignored).

    python scripts/render_mdaa.py --env cevo-aws-mcds                 # fails if any <PLACEHOLDER> is left
    python scripts/render_mdaa.py --env cevo-aws-mcds --allow-placeholders   # CI config validation only

Environment variables override the file: MDAA_<PATH> with dots as underscores, e.g.
MDAA_AWS_ACCOUNT_ID, MDAA_AWS_REGION, MDAA_ORGANIZATION, MDAA_FEATURES_SMUS=true.
That is how GitHub Actions injects per-environment values without editing files.
"""

import argparse
import copy
import json
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOKEN = re.compile(r"\$\{([A-Za-z0-9_.]+)\}")
PLACEHOLDER = re.compile(r"<[A-Z0-9_]+>")


def load_env(name):
    path = os.path.join(ROOT, "config", "environments", f"{name}.yaml")
    env = yaml.safe_load(open(path))
    _apply_overrides(env, "MDAA")
    feats = env.setdefault("features", {})
    # derived feature: QuickSight account subscription only when requested
    env["tags"] = {k: v for k, v in (env.get("tags") or {}).items() if v not in ("", None)}
    feats["quicksight_account_subscription"] = bool(feats.get("quicksight")) and \
        bool((env.get("quicksight") or {}).get("create_account_subscription"))
    return env


def _apply_overrides(node, prefix):
    for k, v in list(node.items()):
        key = f"{prefix}_{k}".upper().replace("-", "_")
        if isinstance(v, dict):
            _apply_overrides(v, key)
        elif os.environ.get(key, "") != "":       # unset/empty variables fall back to the file
            raw = os.environ[key]
            node[k] = {"true": True, "false": False}.get(raw.lower(), raw) if isinstance(v, bool) else raw


def lookup(env, dotted):
    cur = env
    for p in dotted.split("."):
        if not isinstance(cur, dict) or p not in cur:
            raise KeyError(f"environment file has no value for ${{{dotted}}}")
        cur = cur[p]
    return cur


def render(env, allow_placeholders=False, env_name=None):
    text = open(os.path.join(ROOT, "infra", "mdaa.template.yaml")).read()

    def sub(m):
        v = lookup(env, m.group(1))
        return json.dumps(v) if isinstance(v, (dict, list)) else str(v)

    doc = yaml.safe_load(TOKEN.sub(sub, text))
    feats = env.get("features", {})
    for dname in list(doc["domains"]):
        for ename, e in doc["domains"][dname]["environments"].items():
            for mname in list(e["modules"]):
                mod = e["modules"][mname]
                if not _enabled(mod.pop("x-feature", None), feats):
                    del e["modules"][mname]
                    continue
                if "module_configs" in mod:
                    mod["module_configs"] = [c if isinstance(c, str) else c["file"]
                                             for c in mod["module_configs"]
                                             if isinstance(c, str) or _enabled(c.get("x-feature"), feats)]
        if not any(e["modules"] for e in doc["domains"][dname]["environments"].values()):
            del doc["domains"][dname]
    left = sorted(set(PLACEHOLDER.findall(yaml.safe_dump(_used_values(doc)))))
    if left and not allow_placeholders:
        sys.exit(f"Placeholders not set in config/environments/{env_name or env['environment']}.yaml: {', '.join(left)}")
    return doc


def _enabled(feature, feats):
    if not feature:
        return True
    return all(feats.get(f) for f in ([feature] if isinstance(feature, str) else feature))


def _used_values(doc):
    """Only placeholders that end up in used fields matter (e.g. SMUS values when smus is off do not)."""
    d = copy.deepcopy(doc)
    ctx = d.get("context", {})
    used_ctx = set(re.findall(r"\{\{context:([A-Za-z0-9_]+)\}\}", _module_config_text(doc)))
    d["context"] = {k: v for k, v in ctx.items() if k in used_ctx}
    return d


def _module_config_text(doc):
    out = []
    for dom in doc["domains"].values():
        for e in dom["environments"].values():
            for m in e["modules"].values():
                for cfg in m.get("module_configs", []):
                    out.append(open(os.path.join(ROOT, cfg)).read())
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", required=True, help="config/environments/<env>.yaml, e.g. cevo-aws-mcds")
    ap.add_argument("--out", default=os.path.join(ROOT, "mdaa.yaml"))
    ap.add_argument("--allow-placeholders", action="store_true")
    a = ap.parse_args(argv)
    env = load_env(a.env)
    doc = render(env, a.allow_placeholders, a.env)
    with open(a.out, "w") as fh:
        fh.write(f"# GENERATED by scripts/render_mdaa.py --env {a.env} - do not edit; edit infra/ and config/environments/\n")
        yaml.safe_dump(doc, fh, sort_keys=False, width=120)
    mods = [f"{d}/{m}" for d, dom in doc["domains"].items() for e in dom["environments"].values() for m in e["modules"]]
    print(f"rendered {a.out}: {len(mods)} modules -> {', '.join(mods)}")


if __name__ == "__main__":
    main()
